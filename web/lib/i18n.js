/** 取字典文案；缺失 → 中文 → 键名。支持 {name} 插值。 */
export function translate(lang, key, vars) {
  const entry = STRINGS[key];
  let text = entry ? (entry[lang === 'en' ? 1 : 0] || entry[0]) : key;
  if (vars && typeof vars === 'object') {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

/** 编译期自检：确保 zh/en 条目齐全（开发期由 Lead 的脚本复用）。 */
export function auditDictionary() {
  const missing = [];
  for (const [key, entry] of Object.entries(STRINGS)) {
    if (!Array.isArray(entry) || entry.length !== 2 || entry.some((text) => typeof text !== 'string' || text.length === 0)) missing.push(key);
  }
  return missing;
}

export function normalizeLanguage(value) {
  return value === 'en' ? 'en' : 'zh';
}
